/* Pure unread aggregation and account-scope checks; no network or browser required. */
'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, '../js/notifications.js'), 'utf8'), sandbox);
let locale = 'en';
const hub = sandbox.window.GameBoxNotifications.create({ getLocale: () => locale });
hub.setScope('account-a');
const replies = hub.source('feedback', 'menu'), announcements = hub.source('announcements', 'menu');
replies.publish(2); announcements.publish(3);
assert.equal(hub.state('menu').count, 5);
replies.publish(0);
assert(hub.state('menu').unread, 'Reading replies must not clear unread announcements');
assert.equal(hub.state('feedback').unread, false);
announcements.publish(0);
assert.equal(hub.state('menu').unread, false);
replies.publish(20, { atLeast: true }); announcements.publish(1);
assert.equal(hub.describe(hub.state('menu')), 'You have 21+ unread notifications');
assert.throws(() => hub.source('menu', 'feedback'), /notifications\/cycle/);
assert.equal(hub.state('menu').count, 21, 'Rejected topology changes must preserve state');
const replacement = hub.source('feedback', 'menu'); replacement.publish(4);
assert.equal(replies.publish(0), false, 'An older publisher cannot overwrite its replacement');
replies.dispose(); assert.equal(hub.state('feedback').count, 4);
hub.setScope('account-b');
assert.equal(hub.state('menu').count, 0);
assert.equal(replacement.publish(10), false, 'Late old-account callbacks must not relight indicators');
assert.equal(announcements.publish(10), false);
const current = hub.source('announcements', 'menu'); current.publish(2);
replacement.dispose(); assert.equal(hub.state('menu').count, 2);
locale = 'zh'; assert(hub.describe(hub.state('menu')).includes('2'));
current.dispose(); assert.equal(hub.state('menu').unread, false);
assert.equal(current.publish(1), false);
const leaf = hub.source('announcements.release', 'announcements'); leaf.publish(1);
assert(hub.state('menu').unread, 'Descendants must propagate through intermediate groups');
console.log('PASS: independent unread sources, ancestor aggregation, lower-bound counts, replacement publishers, cycle rejection and stale account callbacks.');
