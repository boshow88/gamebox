/* Actual announcement rules and transaction checks. Demo Firestore emulator only. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { createAnnouncementService } from '../js/net/announcements.mjs';
const require = createRequire(new URL('../.cache/feedback-tests/package.json', import.meta.url));
const { initializeTestEnvironment, assertSucceeds, assertFails } = require('@firebase/rules-unit-testing');
const sdk = require('firebase/firestore'); sdk.setLogLevel('silent');
if (!process.env.FIRESTORE_EMULATOR_HOST) throw Error('Use firebase emulators:exec --project demo-gamebox --only firestore');
const [host, port] = process.env.FIRESTORE_EMULATOR_HOST.split(':');
const env = await initializeTestEnvironment({ projectId: 'demo-gamebox', firestore: { host, port: Number(port), rules: readFileSync(new URL('../firestore.rules', import.meta.url), 'utf8') } });
const auth = (uid, email = uid + '@example.com', verified = true) => env.authenticatedContext(uid, { email, email_verified: verified, firebase: { sign_in_provider: 'google.com' } }).firestore();
const admin = auth('admin'), a = auth('a'), b = auth('b'), publicDb = env.unauthenticatedContext().firestore();
const box = (db, uid, anon = false) => createAnnouncementService({ sdk, db, getUser: () => uid ? { uid, anon } : null });
const owner = box(admin, 'admin'), reader = box(a, 'a'), other = box(b, 'b'), visitor = box(publicDb, null);
const ref = (db, id) => sdk.doc(db, 'announcements', id), index = db => sdk.doc(db, 'announcement_meta', 'index');
const content = overrides => ({ title: { zh: '新遊戲上線', en: 'New game' }, body: { zh: '歡迎體驗新遊戲。', en: 'A new game is available.' }, important: true, game: 'darts', published: false, ...overrides });
try {
    await env.clearFirestore();
    await env.withSecurityRulesDisabled(async context => {
        const db = context.firestore();
        await sdk.setDoc(sdk.doc(db, 'config', 'admins'), { members: { 'admin@example.com': { name: 'Admin' } } });
        await sdk.setDoc(sdk.doc(db, 'profiles', 'a'), { birthday: { month: 1, day: 22 }, games: { darts: { best: 50 } } });
    });
    assert.equal((await sdk.getDoc(index(publicDb))).exists(), false);
    const draft = await owner.save(null, content());
    assert.equal(draft.revision, 1);
    assert.equal((await sdk.getDoc(index(publicDb))).exists(), false, 'Draft saves must not write public metadata');
    await assertFails(sdk.getDoc(ref(publicDb, draft.id)));
    await assertFails(sdk.getDoc(ref(a, draft.id)));
    await assertFails(sdk.getDocs(sdk.query(sdk.collection(a, 'announcements'), sdk.limit(20))));
    await assertFails(other.save(null, content({ published: true })));
    await assertFails(box(auth('spoof', 'admin@example.com', false), 'spoof').save(null, content()));
    await assertFails(sdk.setDoc(index(a), { versions: {}, updatedAt: sdk.serverTimestamp() }));
    await assert.rejects(owner.save(null, content({ title: { zh: '', en: '' } })), /invalid-content/);
    await assert.rejects(owner.save(null, content({ body: { zh: '', en: '' } })), /invalid-content/);
    await assert.rejects(owner.save(null, content({ body: { zh: 'x'.repeat(6001), en: '' } })), /invalid-content/);
    const release = await owner.save(draft.id, content({ published: true }), 1);
    assert.equal(release.revision, 2);
    assert.equal((await sdk.getDoc(index(publicDb))).data().versions[draft.id], 2);
    await assertSucceeds(sdk.getDoc(ref(publicDb, draft.id)));
    assert.equal((await visitor.list()).items[0].title.en, 'New game');
    const legacyProfile = (await sdk.getDoc(sdk.doc(a, 'profiles', 'a'))).data();
    assert.equal(legacyProfile.announcementReads, undefined);
    const initialRead = await reader.markRead(draft.id, 2);
    assert(initialRead.saved); assert.equal(initialRead.reads[draft.id], 2);
    const profile = (await sdk.getDoc(sdk.doc(a, 'profiles', 'a'))).data();
    assert.equal(profile.games.darts.best, 50); assert.equal(profile.birthday.day, 22);
    await assertFails(sdk.getDoc(sdk.doc(b, 'profiles', 'a')));
    await assert.rejects(visitor.markRead(draft.id, 2), /sign-in-required/);
    await assert.rejects(box(publicDb, 'guest', true).markRead(draft.id, 2), /sign-in-required/);
    await assertFails(sdk.getDocs(sdk.query(sdk.collection(publicDb, 'announcements'), sdk.where('published', '==', true))));
    await assertFails(sdk.getDocs(sdk.query(sdk.collection(publicDb, 'announcements'), sdk.where('published', '==', true), sdk.limit(51))));
    await assertFails(sdk.deleteDoc(ref(admin, draft.id)));
    await assertFails(sdk.updateDoc(ref(a, draft.id), { title: { en: 'Forged' } }));
    await assertFails(sdk.updateDoc(ref(admin, draft.id), { revision: 3, updatedBy: 'admin', updatedAt: sdk.serverTimestamp() }));
    await assertFails(sdk.updateDoc(ref(admin, draft.id), { published: false, revision: 3, updatedBy: 'admin', updatedAt: sdk.serverTimestamp() }));
    const edited = await owner.save(draft.id, content({ published: true, body: { zh: '內容更新。', en: 'Updated content.' } }), 2);
    assert.equal(edited.revision, 3);
    assert.equal((await sdk.getDoc(index(publicDb))).data().versions[draft.id], 3);
    assert.equal((await reader.markRead(draft.id, 2)).saved, false, 'Old content must not acknowledge a newer publication');
    await assert.rejects(owner.save(draft.id, content(), 2), /announcements\/changed/);
    assert.equal((await reader.markRead(draft.id, 3)).reads[draft.id], 3);
    const second = await owner.save(null, content({ published: true, title: { zh: '', en: 'English only' }, body: { zh: '', en: 'English body' } }));
    await Promise.all([reader.markRead(draft.id, 3), reader.markRead(second.id, 1)]);
    const concurrent = (await sdk.getDoc(sdk.doc(a, 'profiles', 'a'))).data().announcementReads;
    assert.equal(concurrent[draft.id], 3); assert.equal(concurrent[second.id], 1);
    await owner.save(draft.id, content({ published: false }), 3);
    assert.equal((await sdk.getDoc(index(publicDb))).data().versions[draft.id], undefined);
    await assertFails(sdk.getDoc(ref(publicDb, draft.id)));
    assert.equal((await visitor.list()).items.length, 1);
    const beforeDraftEdit = (await sdk.getDoc(index(publicDb))).data().updatedAt.toMillis();
    await owner.save(draft.id, content({ published: false, important: false }), 4);
    assert.equal((await sdk.getDoc(index(publicDb))).data().updatedAt.toMillis(), beforeDraftEdit);
    await owner.remove(draft.id, 5);
    assert.equal((await sdk.getDoc(ref(admin, draft.id))).exists(), false);
    assert.equal((await owner.listAdmin()).items.length, 1);
    const unchanged = await owner.save(null, content({ published: true }));
    const expected = (await sdk.getDoc(index(publicDb))).data().versions;
    await owner.save(second.id, content({ published: true }), 1);
    const arriving = await owner.save(null, content({ published: true }));
    await sdk.setDoc(sdk.doc(b, 'profiles', 'b'), { games: { darts: { best: 12 } }, birthday: { month: 1, day: 22 } });
    const bulk = await other.markAllRead(expected);
    assert.equal(bulk.reads[unchanged.id], 1);
    assert.equal(bulk.reads[second.id], undefined, 'Bulk acknowledgement must not read a revision updated after the click');
    assert.equal(bulk.reads[arriving.id], undefined, 'Bulk acknowledgement must not read announcements published after the click');
    await other.markAllRead((await sdk.getDoc(index(publicDb))).data().versions);
    const afterBulk = (await sdk.getDoc(sdk.doc(b, 'profiles', 'b'))).data();
    assert.equal(afterBulk.announcementReads[second.id], 2); assert.equal(afterBulk.announcementReads[arriving.id], 1);
    assert.equal(afterBulk.announcementReads[unchanged.id], 1); assert.equal(afterBulk.games.darts.best, 12); assert.equal(afterBulk.birthday.day, 22);
    await assert.rejects(visitor.markAllRead(expected), /sign-in-required/);
    await assert.rejects(other.markAllRead({ invalid: 0 }), /invalid-versions/);
    await assert.rejects(other.markAllRead([1]), /invalid-versions/);
    console.log('PASS: public announcements, private drafts, verified-admin publishing, atomic version index, stale editors/readers, concurrent account markers, profile preservation, withdrawal and draft deletion.');
} finally { await env.cleanup(); }
